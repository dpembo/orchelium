const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const outfile = path.join(__dirname, 'agent.js');

esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'src', 'main.js')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  outfile,
  external: [
    'express',
    'mqtt',
    'ws',
    'reconnecting-websocket',
    'jsonwebtoken',
    'jws',
    'uuid',
  ],
  legalComments: 'none',
  banner: {
    js: '/* Generated by npm run build. Edit agent/src and shared/, then rebuild. */\n',
  },
});

const bundled = fs.readFileSync(outfile, 'utf8');
if (/\bjwt\.sign\s*\(/.test(bundled)) {
  fs.unlinkSync(outfile);
  console.error('Refusing to emit agent.js: bundle contains jwt.sign');
  process.exit(1);
}

console.log(`Wrote ${outfile}`);
